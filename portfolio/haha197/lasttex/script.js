function initAuth() {
  if (authInitialized) return;

  if (!window.google || !window.google.accounts || !window.google.accounts.id) {
    authInitAttempts += 1;
    authStatus.textContent = '正在載入 Google OAuth SDK...';
    if (authInitAttempts < MAX_AUTH_INIT_ATTEMPTS) {
      setTimeout(initAuth, 200);
    } else {
      authStatus.textContent = 'Google OAuth SDK 載入逾時，請重新整理頁面。';
    }
    return;
  }

  if (
    !GOOGLE_CLIENT_ID ||
    GOOGLE_CLIENT_ID.startsWith('YOUR_GOOGLE_CLIENT_ID')
  ) {
    authStatus.textContent = '請先在 script.js 設定有效的 GOOGLE_CLIENT_ID。';
    return;
  }

  window.google.accounts.id.initialize({
    client_id: GOOGLE_CLIENT_ID,
    callback: handleGoogleCredential,
    auto_select: true,
    cancel_on_tap_outside: true,
  });

  window.google.accounts.id.renderButton(googleSignin, {
    theme: 'outline',
    size: 'large',
    shape: 'pill',
    width: 250,
    text: 'signin_with',
  });

  if (shouldTriggerAutoReauth()) {
    window.google.accounts.id.prompt();
    markAutoReauthTriggered();
  }

  authInitialized = true;
  authStatus.textContent = '請先使用 Google 帳號登入後再開始遊戲。';
}

function shouldTriggerAutoReauth() {
  try {
    const lastTriggered = Number(localStorage.getItem(AUTO_REAUTH_TS_KEY) || 0);
    if (!Number.isFinite(lastTriggered) || lastTriggered <= 0) {
      return true;
    }

    const elapsed = Date.now() - lastTriggered;
    return elapsed >= AUTO_REAUTH_COOLDOWN_MS;
  } catch (error) {
    return true;
  }
}

function markAutoReauthTriggered() {
  try {
    localStorage.setItem(AUTO_REAUTH_TS_KEY, String(Date.now()));
  } catch (error) {
    // Ignore storage errors and keep auth flow available.
  }
}

function handleGoogleCredential(response) {
  if (!response || !response.credential) {
    authStatus.textContent = '登入失敗，請再試一次。';
    return;
  }

  const payload = decodeJwtPayload(response.credential);
  if (!payload) {
    authStatus.textContent = '無法解析 Google 登入資訊。';
    return;
  }

  isAuthenticated = true;
  currentUserId = payload.sub || '';
  currentUserEmail = payload.email || '';
  currentUserName = payload.name || payload.email || '使用者';
  authStatus.textContent = `已登入：${currentUserName}`;
  hideSyncStatus();
  subtitle.textContent = '已驗證，準備開始雙語文章挑戰';
  updateAuthState();
}

function decodeJwtPayload(credential) {
  try {
    const tokenParts = credential.split('.');
    if (tokenParts.length < 2) return null;
    const base64 = tokenParts[1].replace(/-/g, '+').replace(/_/g, '/');
    const decoded = decodeURIComponent(
      atob(base64)
        .split('')
        .map((char) => `%${`00${char.charCodeAt(0).toString(16)}`.slice(-2)}`)
        .join('')
    );
    return JSON.parse(decoded);
  } catch (error) {
    return null;
  }
}

