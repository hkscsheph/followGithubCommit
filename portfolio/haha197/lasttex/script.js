function loadPassages() {
  passages = typingPassages.map((passage) => ({
    ...passage,
    lines: splitPassageIntoLines(passage.text, passage.title),
  }));
}

function displayPassage() {
  sentenceDisplay.innerHTML = '';
  const currentPassage = passages[currentPassageIndex];
  const totalLines = currentPassage.lines.length;
  const currentLine = currentPassage.lines[currentLineIndex] || '';
  subtitle.textContent = `第 ${currentPassageIndex + 1} / ${
    passages.length
  } 篇 - ${currentPassage.title} - 第 ${
    currentLineIndex + 1
  } / ${totalLines} 行`;

  const lineRow = document.createElement('div');
  lineRow.className = 'passage-line active-line';

  currentLine.split('').forEach((char) => {
    const charSpan = document.createElement('span');
    charSpan.innerText = char;
    lineRow.appendChild(charSpan);
  });

  sentenceDisplay.appendChild(lineRow);
  inputBox.value = '';
  previousInputLength = 0;
  if (gameStarted) {
    inputBox.focus({ preventScroll: true });
  }
}

function checkInput() {
  if (!gameStarted) return;

  const typedValue = inputBox.value;
  const currentPassage = passages[currentPassageIndex];
  const targetLine = currentPassage.lines[currentLineIndex] || '';
  const sentenceChars = sentenceDisplay.querySelectorAll('span');
  let correctChars = 0;

  if (typedValue.length > previousInputLength) {
    const newlyTypedChars = typedValue.length - previousInputLength;
    totalTypedChars += newlyTypedChars;
    for (let i = previousInputLength; i < typedValue.length; i++) {
      if (i < targetLine.length && typedValue[i] === targetLine[i]) {
        totalCorrectTypedChars++;
      }
    }
  }
  previousInputLength = typedValue.length;

  typedValue.split('').forEach((char, index) => {
    if (index < sentenceChars.length) {
      if (char === sentenceChars[index].innerText) {
        sentenceChars[index].classList.add('correct');
        sentenceChars[index].classList.remove('incorrect');
        correctChars++;
      } else {
        sentenceChars[index].classList.add('incorrect');
        sentenceChars[index].classList.remove('correct');
      }
    }
  });

  for (let i = typedValue.length; i < sentenceChars.length; i++) {
    sentenceChars[i].classList.remove('correct', 'incorrect');
  }

  updateLiveStats();

  if (
    typedValue.length === targetLine.length &&
    correctChars === targetLine.length
  ) {
    advanceToNextLine();
  }
}

function advanceToNextLine() {
  const currentPassage = passages[currentPassageIndex];
  currentLineIndex++;

  if (currentLineIndex < currentPassage.lines.length) {
    displayPassage();
    return;
  }

  currentPassageIndex++;
  currentLineIndex = 0;

  if (currentPassageIndex < passages.length) {
    displayPassage();
    return;
  }

  endGame();
}

async function endGame() {
  gameStarted = false;
  clearInterval(timerInterval);
  inputBox.disabled = true;
  const endTime = new Date();
  const timeTaken = (endTime - startTime) / 1000; // in seconds
  timerDisplay.textContent = `時間: ${timeTaken.toFixed(2)}s`;
  const accuracyValue =
    totalTypedChars > 0 ? (totalCorrectTypedChars / totalTypedChars) * 100 : 0;
  const wpmValue =
    timeTaken > 0
      ? Math.round(totalCorrectTypedChars / 5 / (timeTaken / 60))
      : 0;
  accuracy = accuracyValue;
  wpm = wpmValue;
  if (accuracyDisplay) {
    accuracyDisplay.textContent = `準確率: ${accuracy.toFixed(2)}%`;
  }
  subtitle.textContent = '完成雙語文章挑戰';

  const score = Math.round(wpm * (accuracy / 100));
  const record = {
    userId: currentUserId,
    userName: currentUserName,
    userEmail: currentUserEmail,
    language: 'zh-TW+en',
    wpm,
    accuracy: Number(accuracy.toFixed(2)),
    durationSec: Number(timeTaken.toFixed(2)),
    score,
    passageCount: passages.length,
    playedAt: new Date().toISOString(),
  };

  saveRecordToLocalHistory(record);
  renderGameHistory();

  await saveRecordToGoogleSheet(record);
}

function getLocalHistory() {
  try {
    const raw = localStorage.getItem(LOCAL_HISTORY_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (error) {
    return [];
  }
}

function saveRecordToLocalHistory(record) {
  const history = getLocalHistory();
  history.unshift(record);
  const trimmedHistory = history.slice(0, MAX_LOCAL_HISTORY);

  try {
    localStorage.setItem(LOCAL_HISTORY_KEY, JSON.stringify(trimmedHistory));
  } catch (error) {
    showSyncStatus('本機歷史紀錄儲存失敗。', true);
  }
}

function clearGameHistory() {
  try {
    localStorage.removeItem(LOCAL_HISTORY_KEY);
    renderGameHistory();
  } catch (error) {
    showSyncStatus('無法清除本機歷史紀錄。', true);
  }
}

function renderGameHistory() {
  if (!historyList) return;

  const history = getLocalHistory();
  historyList.innerHTML = '';

  if (history.length === 0) {
    const emptyItem = document.createElement('li');
    emptyItem.className = 'history-empty';
    emptyItem.textContent = '目前沒有歷史紀錄，完成一場挑戰後會顯示在這裡。';
    historyList.appendChild(emptyItem);
    return;
  }

  history.forEach((item) => {
    const listItem = document.createElement('li');
    listItem.className = 'history-item';

    const playedAtText = formatPlayedAt(item.playedAt);
    listItem.textContent = `Time played: ${playedAtText} | Duration: ${
      item.durationSec ?? 0
    }s | WPM: ${item.wpm ?? 0}`;
    historyList.appendChild(listItem);
  });
}

function formatPlayedAt(isoString) {
  if (!isoString) return '未知時間';
  const date = new Date(isoString);
  if (Number.isNaN(date.getTime())) return '未知時間';
  return date.toLocaleString('zh-TW', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  });
}

function updateTimer() {
  if (!gameStarted) return;
  updateLiveStats();
}

function updateLiveStats() {
  const timeTaken = (new Date() - startTime) / 1000;
  timerDisplay.textContent = `時間: ${timeTaken.toFixed(2)}s`;

  const accuracyValue =
    totalTypedChars > 0 ? (totalCorrectTypedChars / totalTypedChars) * 100 : 0;
  const safeTimeTaken = timeTaken >= 0.1 ? timeTaken : 0.1;
  const wpmValue = Math.round(
    totalCorrectTypedChars / 5 / (safeTimeTaken / 60)
  );

  accuracy = accuracyValue;
  wpm = wpmValue;
  if (accuracyDisplay) {
    accuracyDisplay.textContent = `準確率: ${accuracy.toFixed(2)}%`;
  }
  wpmDisplay.textContent = `WPM: ${wpm}`;
}

function splitPassageIntoLines(text, title) {
  const maxUnitsPerLine = getLineLengthLimit(title);
  return text.includes(' ')
    ? splitTextByWords(text, maxUnitsPerLine)
    : splitTextByCharacters(text, maxUnitsPerLine);
}

function getLineLengthLimit(title) {
  console.log(
    `Calculating line length limit for title: ${title}, window width: ${window.innerWidth}`
  );
  if (title === '繁體中文文章') {
    return parseInt(window.innerWidth / 18);
  }
  return parseInt(window.innerWidth / 6);
}

function splitTextByCharacters(text, maxCharsPerLine) {
  const lines = [];
  let currentLine = '';

  for (const char of text) {
    currentLine += char;
    if (currentLine.length >= maxCharsPerLine) {
      lines.push(currentLine);
      currentLine = '';
    }
  }

  if (currentLine) {
    lines.push(currentLine);
  }

  return lines;
}

function splitTextByWords(text, maxUnitsPerLine) {
  const tokens = text.match(/\S+\s*/g) || [text];
  const lines = [];
  let currentLine = '';

  tokens.forEach((token) => {
    const trimmedToken = token.trimEnd();
    const nextLine = currentLine + token;

    if (currentLine && nextLine.trimEnd().length > maxUnitsPerLine) {
      lines.push(currentLine.trimEnd());
      currentLine = token;
      return;
    }

    if (!currentLine && trimmedToken.length > maxUnitsPerLine) {
      const brokenWordLines = splitTextByCharacters(
        trimmedToken,
        maxUnitsPerLine
      );
      lines.push(...brokenWordLines.slice(0, -1));
      currentLine = brokenWordLines[brokenWordLines.length - 1];
      return;
    }

    currentLine = nextLine;
  });

  if (currentLine.trim().length > 0) {
    lines.push(currentLine.trimEnd());
  }

  return lines;
}

async function saveRecordToGoogleSheet(record) {
  if (
    !APPS_SCRIPT_WEB_APP_URL ||
    APPS_SCRIPT_WEB_APP_URL.startsWith(
      'PASTE_YOUR_APPS_SCRIPT_WEB_APP_URL_HERE'
    )
  ) {
    showSyncStatus('尚未設定 Google Sheet Web App URL，成績未上傳。', true);
    return;
  }

  try {
    const form = new URLSearchParams();
    form.set('userId', record.userId || '');
    form.set('userName', record.userName || '');
    form.set('userEmail', record.userEmail || '');
    form.set('language', record.language || '');
    form.set('wpm', String(record.wpm ?? ''));
    form.set('accuracy', String(record.accuracy ?? ''));
    form.set('durationSec', String(record.durationSec ?? ''));
    form.set('score', String(record.score ?? ''));
    form.set('passageCount', String(record.passageCount ?? ''));

    // Apps Script Web App often requires no-cors when called from static hosting.
    await fetch(APPS_SCRIPT_WEB_APP_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded;charset=UTF-8',
      },
      body: form.toString(),
      mode: 'no-cors',
    });

    showSyncStatus('成績已送出到 Google Sheet。');
  } catch (error) {
    showSyncStatus('成績上傳失敗，請檢查網路或 Apps Script 設定。', true);
  }
}
